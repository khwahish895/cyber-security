import React, { useState } from 'react';
import {
  Bell,
  Search,
  Filter,
  CheckCircle2,
  Clock,
  AlertTriangle,
  ShieldAlert,
  MessageSquare,
  ArrowRight,
  ExternalLink,
  ChevronRight
} from 'lucide-react';
import { SecurityAlert, AlertStatus, Severity, TrafficFlow } from '../types';

interface AlertsCenterPageProps {
  alerts: SecurityAlert[];
  onUpdateAlert: (id: string, status: AlertStatus, note?: string) => void;
  onInspectFlow: (flowId: string) => void;
}

export const AlertsCenterPage: React.FC<AlertsCenterPageProps> = ({
  alerts,
  onUpdateAlert,
  onInspectFlow
}) => {
  const [statusFilter, setStatusFilter] = useState<string>('ALL');
  const [severityFilter, setSeverityFilter] = useState<string>('ALL');
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedAlert, setSelectedAlert] = useState<SecurityAlert | null>(null);
  const [noteInput, setNoteInput] = useState('');

  const filteredAlerts = alerts.filter((a) => {
    if (statusFilter !== 'ALL' && a.status !== statusFilter) return false;
    if (severityFilter !== 'ALL' && a.severity !== severityFilter) return false;
    if (searchTerm) {
      const q = searchTerm.toLowerCase();
      const match =
        a.id.toLowerCase().includes(q) ||
        a.title.toLowerCase().includes(q) ||
        a.flowId.toLowerCase().includes(q) ||
        a.threatClass.toLowerCase().includes(q);
      if (!match) return false;
    }
    return true;
  });

  const handleAddNote = (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedAlert || !noteInput.trim()) return;
    onUpdateAlert(selectedAlert.id, selectedAlert.status, noteInput.trim());
    setNoteInput('');
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 pb-2 border-b border-slate-800">
        <div>
          <h1 className="text-xl font-bold tracking-tight text-white flex items-center gap-2">
            <span>Security Alerts &amp; Incident Triage</span>
            <span className="text-xs font-mono font-normal text-slate-400">
              · {filteredAlerts.length} Active Notifications
            </span>
          </h1>
          <p className="text-xs text-slate-400 mt-0.5">
            Prioritized notifications generated by unidirectional flow anomaly spikes and model classifications.
          </p>
        </div>

        <div className="flex items-center gap-2">
          {/* Status Quick Filter Buttons */}
          <div className="inline-flex rounded-lg bg-slate-900 border border-slate-800 p-0.5 text-xs font-medium">
            {['ALL', 'new', 'investigating', 'acknowledged', 'resolved'].map((s) => (
              <button
                key={s}
                onClick={() => setStatusFilter(s)}
                className={`px-2.5 py-1 rounded capitalize transition-colors ${
                  statusFilter === s ? 'bg-cyan-500/20 text-cyan-400 font-semibold' : 'text-slate-400 hover:text-slate-200'
                }`}
              >
                {s}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Search and Secondary Filter */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 text-xs">
        <div className="relative sm:col-span-2">
          <Search className="w-4 h-4 text-slate-500 absolute left-3 top-2.5" />
          <input
            type="text"
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            placeholder="Search Alert ID, flow, threat type, or description..."
            className="w-full pl-9 pr-3 py-2 rounded-lg bg-slate-900 border border-slate-800 text-slate-200 placeholder-slate-500 focus:outline-none focus:border-cyan-500"
          />
        </div>

        <div>
          <select
            value={severityFilter}
            onChange={(e) => setSeverityFilter(e.target.value)}
            className="w-full px-3 py-2 rounded-lg bg-slate-900 border border-slate-800 text-slate-200 focus:outline-none focus:border-cyan-500"
          >
            <option value="ALL">All Severities</option>
            <option value="critical">Critical</option>
            <option value="high">High</option>
            <option value="medium">Medium</option>
            <option value="low">Low</option>
          </select>
        </div>
      </div>

      {/* Split View: Alert List & Selected Alert Details */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Left 2 Columns: Alerts List */}
        <div className="lg:col-span-2 space-y-3">
          {filteredAlerts.length === 0 ? (
            <div className="p-12 text-center rounded-xl bg-slate-900/40 border border-slate-800 text-xs text-slate-500">
              No security alerts found matching the current filters.
            </div>
          ) : (
            filteredAlerts.map((alert) => {
              const isSelected = selectedAlert?.id === alert.id;
              return (
                <div
                  key={alert.id}
                  onClick={() => setSelectedAlert(alert)}
                  className={`p-4 rounded-xl border transition-all text-xs cursor-pointer ${
                    isSelected
                      ? 'bg-cyan-500/10 border-cyan-500/50 shadow-lg shadow-cyan-500/5'
                      : 'bg-slate-900/60 border-slate-800 hover:bg-slate-800/60 hover:border-slate-700'
                  }`}
                >
                  <div className="flex items-start justify-between gap-3">
                    <div className="flex items-center gap-2.5">
                      <span
                        className={`px-2 py-0.5 rounded text-[10px] font-mono font-bold uppercase ${
                          alert.severity === 'critical' ? 'bg-red-500/20 text-red-400 border border-red-500/30' :
                          alert.severity === 'high' ? 'bg-orange-500/20 text-orange-400 border border-orange-500/30' :
                          'bg-amber-500/20 text-amber-400 border border-amber-500/30'
                        }`}
                      >
                        {alert.severity}
                      </span>
                      <span className="font-semibold text-white text-sm">{alert.title}</span>
                    </div>

                    <div className="flex items-center gap-2 shrink-0">
                      <span className="font-mono text-xs text-slate-400">
                        Risk: <strong className="text-white font-bold">{alert.riskScore}</strong>
                      </span>
                      <span
                        className={`px-2 py-0.5 rounded text-[10px] capitalize font-medium ${
                          alert.status === 'new' ? 'bg-red-500/15 text-red-300' :
                          alert.status === 'investigating' ? 'bg-indigo-500/15 text-indigo-300' :
                          alert.status === 'acknowledged' ? 'bg-amber-500/15 text-amber-300' :
                          'bg-emerald-500/15 text-emerald-300'
                        }`}
                      >
                        {alert.status}
                      </span>
                    </div>
                  </div>

                  <p className="text-slate-300 mt-2 line-clamp-2 leading-relaxed">
                    {alert.description}
                  </p>

                  <div className="mt-3 pt-2.5 border-t border-slate-800/80 flex items-center justify-between text-[11px] text-slate-400 font-mono">
                    <div className="flex items-center gap-3">
                      <span>{alert.id}</span>
                      <span>·</span>
                      <span>Flow: <strong className="text-cyan-400">{alert.flowId}</strong></span>
                    </div>
                    <span>{new Date(alert.timestamp).toLocaleTimeString()}</span>
                  </div>
                </div>
              );
            })
          )}
        </div>

        {/* Right 1 Column: Detail & Investigation Panel */}
        <div>
          {selectedAlert ? (
            <div className="p-5 rounded-xl bg-slate-900/80 border border-slate-800 space-y-4 text-xs sticky top-24">
              <div className="flex items-center justify-between border-b border-slate-800 pb-3">
                <div>
                  <span className="font-mono text-cyan-400 font-semibold">{selectedAlert.id}</span>
                  <h3 className="font-bold text-white text-sm mt-0.5">{selectedAlert.title}</h3>
                </div>
                <span
                  className={`px-2 py-0.5 rounded text-[10px] font-mono uppercase font-bold ${
                    selectedAlert.severity === 'critical' ? 'bg-red-500/20 text-red-400' : 'bg-amber-500/20 text-amber-400'
                  }`}
                >
                  {selectedAlert.severity}
                </span>
              </div>

              <div>
                <span className="text-[11px] text-slate-400 block mb-1">Diagnostic Explanation</span>
                <p className="text-slate-300 leading-relaxed bg-slate-950 p-3 rounded-lg border border-slate-800">
                  {selectedAlert.description}
                </p>
              </div>

              <div className="grid grid-cols-2 gap-2">
                <div className="p-2.5 rounded bg-slate-950 border border-slate-800">
                  <span className="text-[10px] text-slate-400 block">Correlated Flow</span>
                  <span className="font-mono text-cyan-400 font-semibold">{selectedAlert.flowId}</span>
                </div>
                <div className="p-2.5 rounded bg-slate-950 border border-slate-800">
                  <span className="text-[10px] text-slate-400 block">Risk Score</span>
                  <span className="font-mono text-white font-bold">{selectedAlert.riskScore}/100</span>
                </div>
              </div>

              {/* Status transition controls */}
              <div className="space-y-1.5 pt-2 border-t border-slate-800">
                <span className="text-[11px] text-slate-400 block">Update Status</span>
                <div className="grid grid-cols-3 gap-2">
                  <button
                    onClick={() => onUpdateAlert(selectedAlert.id, 'investigating')}
                    className={`py-1.5 rounded text-[11px] font-medium transition-colors ${
                      selectedAlert.status === 'investigating'
                        ? 'bg-indigo-600 text-white'
                        : 'bg-slate-800 text-slate-300 hover:bg-slate-700'
                    }`}
                  >
                    Investigating
                  </button>
                  <button
                    onClick={() => onUpdateAlert(selectedAlert.id, 'acknowledged')}
                    className={`py-1.5 rounded text-[11px] font-medium transition-colors ${
                      selectedAlert.status === 'acknowledged'
                        ? 'bg-amber-600 text-white'
                        : 'bg-slate-800 text-slate-300 hover:bg-slate-700'
                    }`}
                  >
                    Acknowledge
                  </button>
                  <button
                    onClick={() => onUpdateAlert(selectedAlert.id, 'resolved')}
                    className={`py-1.5 rounded text-[11px] font-medium transition-colors ${
                      selectedAlert.status === 'resolved'
                        ? 'bg-emerald-600 text-white'
                        : 'bg-slate-800 text-slate-300 hover:bg-slate-700'
                    }`}
                  >
                    Resolve
                  </button>
                </div>
              </div>

              {/* Correlate flow in explorer */}
              <button
                onClick={() => onInspectFlow(selectedAlert.flowId)}
                className="w-full py-2 rounded-lg bg-cyan-600 hover:bg-cyan-500 text-white font-semibold transition-colors flex items-center justify-center gap-1.5"
              >
                <span>Inspect Underlying Unidirectional Flow</span>
                <ArrowRight className="w-3.5 h-3.5" />
              </button>

              {/* Investigation notes log */}
              <div className="space-y-2 pt-2 border-t border-slate-800">
                <span className="text-[11px] text-slate-400 block">Investigation Comments</span>
                <div className="space-y-1.5 max-h-36 overflow-y-auto">
                  {selectedAlert.notes && selectedAlert.notes.length > 0 ? (
                    selectedAlert.notes.map((note, idx) => (
                      <div key={idx} className="p-2 rounded bg-slate-950 text-[11px] text-slate-300 border border-slate-800/80">
                        {note}
                      </div>
                    ))
                  ) : (
                    <div className="text-[11px] text-slate-500 italic">No notes recorded yet.</div>
                  )}
                </div>

                <form onSubmit={handleAddNote} className="flex gap-2 mt-2">
                  <input
                    type="text"
                    value={noteInput}
                    onChange={(e) => setNoteInput(e.target.value)}
                    placeholder="Add comment..."
                    className="flex-1 px-2.5 py-1.5 rounded bg-slate-950 border border-slate-800 text-slate-200 focus:outline-none focus:border-cyan-500 text-xs"
                  />
                  <button
                    type="submit"
                    className="px-3 py-1.5 rounded bg-slate-800 hover:bg-slate-700 text-slate-200 font-medium text-xs transition-colors"
                  >
                    Add
                  </button>
                </form>
              </div>
            </div>
          ) : (
            <div className="p-8 text-center rounded-xl bg-slate-900/40 border border-slate-800 text-xs text-slate-500">
              Select an alert from the list to view diagnostic metadata, feature correlation, and update triage status.
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
